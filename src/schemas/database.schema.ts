/**
 * Option Lists Collection Schema
 * 
 * Collection ID: option_lists
 * Purpose: Store generated college recommendations for students
 */
export interface OptionListSchema {
    $id?: string;

    // Student Reference
    studentId: string; // Links to students collection
    userId: string; // Links to user_profiles

    // Generated Options (stored as JSON)
    safeColleges: string; // JSON string of ScoredCollege[]
    targetColleges: string; // JSON string of ScoredCollege[]
    reachColleges: string; // JSON string of ScoredCollege[]

    // Metadata
    generatedAt: string;
    examType: string; // UGCET | UGNEET
    totalOptions: number;

    // Timestamps
    $createdAt?: string;
    $updatedAt?: string;
}

/**
 * Appwrite Collection Attributes for option_lists:
 * 
 * 1. studentId (string, 36, required)
 * 2. userId (string, 36, required)
 * 3. safeColleges (string, 50000) - JSON
 * 4. targetColleges (string, 50000) - JSON
 * 5. reachColleges (string, 50000) - JSON
 * 6. generatedAt (datetime)
 * 7. examType (enum: ['UGCET', 'UGNEET'])
 * 8. totalOptions (integer)
 * 
 * Indexes:
 * - studentId
 * - userId
 * - examType
 */

