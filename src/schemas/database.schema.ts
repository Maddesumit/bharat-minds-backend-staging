/**
 * Students Collection Schema
 * 
 * Collection ID: students
 * Purpose: Complete student registration data for counselling
 */
export interface StudentSchema {
    $id?: string;

    // User Reference
    userId: string; // Links to user_profiles

    // Personal Info
    name: string;
    mobile: string;
    email: string;

    // Counselling Information
    counsellingTypes: string[]; // Array of CounsellingType

    // UGCET Data
    ugcetCourses?: string[]; // Array of course names
    farmScienceCourses?: string[];

    // UGNEET Data
    ugneetCourses?: string; // JSON string of UGNEETCourseSelection[]
    ugneetSpecialCategories?: string[]; // Array of special categories
    neetAIR?: number; // All India Rank

    // Ranks (stored as JSON)
    courseRanks: string; // JSON string of CourseRank[]

    // Category Information
    baseCategory: string; // BaseCategory enum value
    hasKannada: boolean;
    hasRural: boolean;
    hasHK: boolean; // Hyderabad-Karnataka region
    snqApplied?: boolean; // SNQ Quota
    incomeSlab?: string;
    eligibleCategories: string; // JSON string of CategoryVariant[]
    specialCategories: string; // JSON string of SpecialCategory[]

    // Timestamps
    $createdAt?: string;
    $updatedAt?: string;
}

/**
 * Appwrite Collection Attributes for students:
 * 
 * 1. userId (string, 36, required)
 * 2. name (string, 255, required)
 * 3. mobile (string, 20, required)
 * 4. email (email, 255, required)
 * 5. counsellingTypes (string[], array)
 * 6. ugcetCourses (string[], array)
 * 7. farmScienceCourses (string[], array)
 * 8. ugneetCourses (string, 5000) - JSON
 * 9. ugneetSpecialCategories (string[], array)
 * 10. neetAIR (integer)
 * 11. courseRanks (string, 10000) - JSON
 * 12. baseCategory (string, 10)
 * 13. hasKannada (boolean, default: false)
 * 14. hasRural (boolean, default: false)
 * 15. hasHK (boolean, default: false)
 * 16. snqApplied (boolean)
 * 17. incomeSlab (string, 50)
 * 18. eligibleCategories (string, 5000) - JSON
 * 19. specialCategories (string, 1000) - JSON
 * 
 * Indexes:
 * - userId
 * - email
 * - mobile
 * - baseCategory (for filtering)
 */

