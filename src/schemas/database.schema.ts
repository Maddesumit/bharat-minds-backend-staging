/**
 * User Profiles Collection Schema
 * 
 * Collection ID: user_profiles
 * Purpose: Extended user profile information beyond basic auth
 */
export interface UserProfileSchema {
    // Primary Key (auto-generated by Appwrite)
    $id?: string;

    // Foreign Key - Links to Appwrite Auth User
    userId: string; // Required, indexed, unique

    // Basic Info (synced from Auth)
    name: string; // Required
    email: string; // Required, indexed
    phone?: string;

    // Educational Background
    college?: string; // Index recommended for search
    city?: string;
    state?: string;
    currentYear?: string; // e.g., "12th", "1st Year"
    stream?: string; // e.g., "Science (PCM)", "Commerce"

    // Career Counselling
    examType?: string; // UGCET | UGNEET | COMBINED
    preferredLanguage?: string; // English | Kannada | Hindi | Telugu

    // Additional Contact
    guardianName?: string;
    guardianPhone?: string;

    // Metadata
    profileCompleted: boolean; // Default: false
    registrationCompleted: boolean; // Default: false

    // Timestamps (auto-managed by Appwrite)
    $createdAt?: string;
    $updatedAt?: string;
}

/**
 * Appwrite Collection Attributes for user_profiles:
 * 
 * 1. userId (string, 36, required, unique)
 * 2. name (string, 255, required)
 * 3. email (email, 255, required)
 * 4. phone (string, 20)
 * 5. college (string, 255)
 * 6. city (string, 100)
 * 7. state (string, 100)
 * 8. currentYear (string, 50)
 * 9. stream (string, 100)
 * 10. examType (enum: ['UGCET', 'UGNEET', 'COMBINED'])
 * 11. preferredLanguage (enum: ['English', 'Kannada', 'Hindi', 'Telugu'])
 * 12. guardianName (string, 255)
 * 13. guardianPhone (string, 20)
 * 14. profileCompleted (boolean, default: false)
 * 15. registrationCompleted (boolean, default: false)
 * 
 * Indexes:
 * - userId (unique)
 * - email
 * - college (for search)
 * - examType (for filtering)
 */

